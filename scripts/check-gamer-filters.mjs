import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import Filters from '../dist/gamer-filters.js';
import {collectGamerClassifications} from './gamer-classifications.mjs';
const wait=async()=>{},fixture=id=>({animeSn:id}),raw={items:[fixture(1),fixture(2),fixture(3)]};
const option={field:'tags',value:'動作',label:'动作',property:'attributes'};
const collect=readPage=>collectGamerClassifications(raw,{readPage,wait,options:[option]});
const pages=[{totalPage:2,animeList:[fixture(1),fixture(2)]},{totalPage:2,animeList:[fixture(3)]}];
const complete=await collect(async(o,page)=>pages[page-1]);
assert.deepEqual(complete.items[1].attributes,['動作']);assert.equal(complete.meta.checkedFilters,1);
let calls=0;
const reordered=await collect(async(o,page)=>++calls===3?{...pages[0],animeList:[fixture(3),fixture(1)]}:pages[page-1]);
assert.deepEqual(reordered.items,complete.items,'Harmless ordering changes must not lose membership');
const sorts=[];
const recovered=await collect(async(o,page,sort)=>{sorts.push(sort);return sort===1?(page===1?pages[0]:{totalPage:2,animeList:[fixture(2)]}):pages[page-1];});
assert.deepEqual(recovered.items,complete.items);assert.deepEqual(sorts,[1,1,2,2,2]);
calls=0;
await assert.rejects(collect(async(o,page)=>{calls++;return page===1?pages[0]:{totalPage:2,animeList:[fixture(2)]};}),/唯一 ID 不足/);assert.equal(calls,6,'Broken pagination stops after three attempts');
await assert.rejects(collect(async(o,page)=>page===1?pages[0]:{totalPage:2,animeList:[]}),/分页不完整/);
await assert.rejects(collect(async()=>({totalPage:1,animeList:[fixture(-1)]})),/ID 无效/);
const empty=await collect(async()=>({totalPage:0,animeList:[]}));assert.deepEqual(empty.items[1].attributes,[]);
const foreign=await collect(async()=>({totalPage:1,animeList:[fixture(999)]}));assert.deepEqual(foreign.items[1].attributes,[],'A filtered list must not introduce titles outside the validated main directory');
const item={classification:{attributes:['動作','科幻'],types:['電影'],audiences:['年齡限制']}};
assert(Filters.matches(item,{attributes:['動作','科幻'],type:'電影',target:'年齡限制'}));
assert(!Filters.matches(item,{attributes:['動作','戀愛']}));assert(!Filters.matches(item,{type:'OVA'}));
assert(Filters.matches({},Filters.defaults));assert(!Filters.matches({},{attributes:['動作']}));
assert(Filters.searchText(item).includes('动作'));assert(Filters.searchText(item).includes('电影'));
assert.equal(Filters.options.length,42);assert.equal(Filters.groups[0].options.length,35);
const root=new URL('../',import.meta.url),sea=JSON.parse(await readFile(new URL('dist/catalog.json',root),'utf8')),gamer=JSON.parse(await readFile(new URL('dist/gamer-catalog.json',root),'utf8'));
assert.equal(sea.items.find(x=>x.intlId===37549).contentType,'non-animation');assert.equal(sea.items.find(x=>x.intlId===2080019).contentType,'animation');
for(const x of gamer.items){assert(x.classification);assert.equal(x.contentType,x.classification.types.includes('真人演出')?'non-animation':'animation');}
console.log(JSON.stringify({gamerCategoryChecks:'passed',filters:Filters.options.length,pagination:'complete, reordered, retried, truncated and unknown IDs',annotations:'verified'}));
